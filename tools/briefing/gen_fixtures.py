"""Writes tests/briefing_fixtures.inc: the part of decoded variant bricks that fr::FindBriefingMutes looks at.

Input: ResourceTool's JSON of each brick's TEMP and TBLU (ResourceTool HM3 convert TEMP|TBLU <file> <out.json>) and
each TEMP's resource header references, from the rpkg metadata. `--refs-dir` names a directory holding a module
summ.py of your own whose refs_for(temp_hash) returns that TEMP's references as a list of resource hashes (ints), in
header order; any rpkg metadata reader can back it.

For each brick: every ZGameEventListenerEntity (zgameeventlistenerentity.class) with its m_eEvent (-1 when the brick
leaves it at the class default), every DianaSpeak instance (dianaspeak or ldhelper_dianaspeak_interruptible), every
entity a signal from a listener can reach within kBriefingMaxSteps + 1 links, and every connection and output
forwarding out of those entities. That is all FindBriefingMutes follows, so the test sees what the game's blueprint
would give it.

Usage: python3 -I tools/briefing/gen_fixtures.py --refs-dir <dir> --json <dir> <TEMP hex>:<name> ... > tests/briefing_fixtures.inc
"""
import argparse
import collections
import json
import os
import sys

LISTENER = 0x003BF79A94EBFCE7  # [modules:/zgameeventlistenerentity.class]
SPEAKERS = {0x00C25939D55B4D55, 0x003626A7D93B0D5D}  # dianaspeak, ldhelper_dianaspeak_interruptible (TEMP)
EVENTS = {"GET_GameplayStart": 0, "GET_GameplayStop": 1, "GET_IntroCutStart": 2, "GET_IntroCutEnd": 3,
          "GET_ProfilingStart": 4, "GET_SavegameRestored": 5, "GET_PlayingAfterLoad": 6}
REACH = 6  # kBriefingMaxSteps + 1


def props(se):
    return {p["nPropertyID"]: p["value"] for p in se["propertyValues"] + se["postInitPropertyValues"]}


def cstr(s):
    return json.dumps(s, ensure_ascii=True)


def fixture(refs_for, jdir, temp, name):
    T = json.load(open(os.path.join(jdir, "%016X.TEMP.json" % temp)))
    refs = refs_for(temp)
    B = json.load(open(os.path.join(jdir, "%016X.TBLU.json" % refs[T["blueprintIndexInResourceHeader"]])))
    kinds, events = [], []
    for se in T["subEntities"]:
        t = refs[se["entityTypeResourceIndex"]]
        if t == LISTENER:
            kinds.append("L")
            ev = props(se).get("m_eEvent", {}).get("$val")
            events.append(EVENTS[ev] if ev is not None else -1)
        else:
            kinds.append("S" if t in SPEAKERS else "O")
            events.append(-1)
    links = [(c["fromID"], c["fromPinName"], c["toID"], c["toPinName"], "C") for c in B["pinConnections"]]
    links += [(c["fromID"], c["fromPinName"], c["toID"], c["toPinName"], "O") for c in B["outputPinForwardings"]]
    out = collections.defaultdict(list)
    for l in links:
        out[l[0]].append(l)
    reach = set()
    front = [(i, 0) for i, k in enumerate(kinds) if k == "L"]
    while front:
        n, d = front.pop(0)
        if n in reach:
            continue
        reach.add(n)
        if d < REACH and kinds[n] != "S":
            front.extend((l[2], d + 1) for l in out[n])
    keep = [l for l in links if l[0] in reach]
    nodes = sorted(reach | {l[2] for l in keep} | {i for i, k in enumerate(kinds) if k != "O"})
    lines = ["    {%s, 0x%016XULL, %d,\n     {" % (cstr(name), temp, len(kinds))]
    for i in nodes:
        lines.append("      {%d, 0x%016XULL, '%s', %d, %s}," % (
            i, B["subEntities"][i]["entityId"], kinds[i], events[i], cstr(B["subEntities"][i]["entityName"])))
    lines.append("     },\n     {")
    for f, fp, t, tp, k in keep:
        lines.append("      {%d, %s, %d, %s, '%s'}," % (f, cstr(fp), t, cstr(tp), k))
    lines.append("     }},")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--refs-dir", required=True, help="directory with summ.py: refs_for(temp_hash) -> header refs")
    ap.add_argument("--json", required=True, help="directory of ResourceTool <HASH>.TEMP.json / .TBLU.json files")
    ap.add_argument("bricks", nargs="+")
    a = ap.parse_args()
    sys.path.insert(0, a.refs_dir)
    import summ  # noqa: E402 (the reference reader named by --refs-dir)
    print("// Generated by tools/briefing/gen_fixtures.py from decoded brick TEMP/TBLU pairs; do not edit.")
    print("// {brick, TEMP rid, sub-entity count, {index, id, kind (L listener, S DianaSpeak, O other), m_eEvent")
    print("// (-1: the class default), name}, {from, pin, to, pin, kind (C connection, O output forwarding)}}")
    print("static const BriefingFixture kBriefingFixtures[] = {")
    for b in a.bricks:
        h, name = b.split(":")
        print(fixture(summ.refs_for, a.json, int(h, 16), name))
    print("};")


if __name__ == "__main__":
    main()
